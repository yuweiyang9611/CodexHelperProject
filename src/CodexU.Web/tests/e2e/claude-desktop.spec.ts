import { expect, test } from '@playwright/test'
import { openTab, settleUi } from './demo'

test('Desktop quota samples and manual subscription are clear in both views', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'chromium-dark-100', 'One explicit synthetic scenario covers Desktop source presentation.')
  await page.clock.setFixedTime(new Date('2026-11-01T18:40:00+09:00'))
  await page.goto('/?visualTest=1&theme=dark&claudeDesktopQuota=1&claudeManualMonthly=100')
  await page.getByRole('button', { name: 'Claude Code', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Claude Code', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.overview-grid')).toBeVisible()
  await settleUi(page)

  const overview = page.locator('.overview-grid')
  const quota = overview.locator('.quota-card')
  await expect(quota.locator('.quota-caption')).toHaveText(['采样剩余', '采样剩余'])
  await expect(quota.locator('.quota-content > strong')).toHaveText(['73%', '18%'])
  await expect(quota.locator('.sample-time time')).toHaveText(['2026/11/01 18:35:00', '2026/11/01 18:35:00'])
  await expect(quota.locator('.sample-time').first()).toContainText('本地时间 · 非实时')
  await expect(quota.locator('.reset-time')).toHaveText(['来源未提供重置时间', '来源未提供重置时间'])
  await expect(quota).toContainText('超过 30 分钟')
  await expect(quota).toContainText('订阅档位未识别')
  await expect(quota.locator('.burn-down')).toHaveCount(0)
  await expect(overview.locator('.quota-risk-notice')).toHaveCount(0)
  await page.getByRole('button', { name: '展开明细' }).click()
  await expect(overview.locator('.value-summary-grid')).toContainText('订阅月费 · 手动')
  await expect(overview.locator('.value-summary-grid')).toContainText('US$100.00')
  await settleUi(page)
  const overviewPath = testInfo.outputPath('claude-desktop-overview.png')
  await overview.screenshot({ path: overviewPath, animations: 'disabled' })
  await testInfo.attach('Desktop overview', { path: overviewPath, contentType: 'image/png' })

  await openTab(page, 'combined')
  const columns = page.locator('.combined-columns')
  const claude = columns.locator('.combined-runtime-column').filter({ has: page.locator('header > strong', { hasText: 'Claude Code' }) })
  await expect(claude.locator('.quota-caption')).toHaveText(['采样剩余', '采样剩余'])
  await expect(claude.locator('.sample-time time')).toHaveText(['2026/11/01 18:35:00', '2026/11/01 18:35:00'])
  await expect(claude.locator('.reset-time')).toHaveText(['来源未提供重置时间', '来源未提供重置时间'])
  await expect(claude.locator('.burn-down')).toHaveCount(0)
  await expect(claude).toContainText('本地 Claude Desktop 历史仅提供额度百分比')
  await expect(claude).toContainText('US$100.00 · 手动')
  const combinedPath = testInfo.outputPath('claude-desktop-combined.png')
  await columns.screenshot({ path: combinedPath, animations: 'disabled' })
  await testInfo.attach('Desktop combined columns', { path: combinedPath, contentType: 'image/png' })

  const costs = page.locator('.combined-card').filter({ has: page.getByRole('heading', { name: '合计成本', exact: true }) })
  await expect(costs).toContainText('含手动值')
  await expect(costs).toContainText('US$300.00')
  await expect(costs).toContainText('不代表实际账单')
  const costsPath = testInfo.outputPath('claude-desktop-combined-costs.png')
  await costs.screenshot({ path: costsPath, animations: 'disabled' })
  await testInfo.attach('Desktop combined cost estimates', { path: costsPath, contentType: 'image/png' })
})
