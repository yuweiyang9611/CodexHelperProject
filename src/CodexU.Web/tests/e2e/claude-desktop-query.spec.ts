import { expect, test } from '@playwright/test'
import { openTab, settleUi } from './demo'

test('Desktop get_usage snapshot shows reported resets and preserves the manual subscription', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'chromium-dark-100', 'One explicit synthetic scenario covers Desktop query snapshots.')
  await page.clock.setFixedTime(new Date('2026-11-01T18:40:00+09:00'))
  await page.goto('/?visualTest=1&theme=dark&claudeDesktopQuery=1')
  await page.getByRole('button', { name: 'Claude Code', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Claude Code', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await settleUi(page)

  const overview = page.locator('.overview-grid')
  const quota = overview.locator('.quota-card')
  await expect(quota.locator('.quota-caption')).toHaveText(['查询时剩余', '查询时剩余'])
  await expect(quota.locator('.quota-content > strong')).toHaveText(['73%', '18%'])
  await expect(quota.locator('.sample-time time')).toHaveText(['读取于 2026/11/01 18:35:00', '读取于 2026/11/01 18:35:00'])
  await expect(quota.locator('.reset-time')).toHaveText(['2 小时后重置', '3 天后重置'])
  await expect(quota).toContainText('Desktop 查询快照')
  await expect(quota).toContainText('60 秒')
  await expect(quota).toContainText('15 分钟')
  await expect(quota).not.toContainText('历史仅提供额度百分比')
  await expect(quota).not.toContainText('来源未提供重置时间')
  await expect(quota.locator('.burn-down')).toHaveCount(0)
  await expect(overview.locator('.quota-risk-notice')).toHaveCount(0)
  await page.getByRole('button', { name: '展开明细' }).click()
  await expect(overview.locator('.value-summary-grid')).toContainText('订阅月费 · 手动')
  await expect(overview.locator('.value-summary-grid')).toContainText('US$100.00')
  await settleUi(page)
  const overviewPath = testInfo.outputPath('claude-desktop-query-overview.png')
  await overview.screenshot({ path: overviewPath, animations: 'disabled' })
  await testInfo.attach('Desktop query overview', { path: overviewPath, contentType: 'image/png' })

  await openTab(page, 'combined')
  const columns = page.locator('.combined-columns')
  const claude = columns.locator('.combined-runtime-column').filter({ has: page.locator('header > strong', { hasText: 'Claude Code' }) })
  await expect(claude.locator('.quota-caption')).toHaveText(['查询时剩余', '查询时剩余'])
  await expect(claude.locator('.sample-time time')).toHaveText(['读取于 2026/11/01 18:35:00', '读取于 2026/11/01 18:35:00'])
  await expect(claude.locator('.reset-time')).toHaveText(['2 小时后重置', '3 天后重置'])
  await expect(claude.locator('.burn-down')).toHaveCount(0)
  await expect(claude).toContainText('Desktop 查询快照')
  await expect(claude).toContainText('US$100.00 · 手动')
  await expect(claude).not.toContainText('历史仅提供额度百分比')
  await expect(claude).not.toContainText('来源未提供重置时间')
  await expect(page.locator('.combined-earliest')).not.toContainText('Claude Code')
  const costs = page.locator('.combined-card').filter({ has: page.getByRole('heading', { name: '合计成本', exact: true }) })
  await expect(costs).toContainText('US$300.00')
  await expect(costs).toContainText('含手动值')
  const combinedPath = testInfo.outputPath('claude-desktop-query-combined.png')
  await columns.screenshot({ path: combinedPath, animations: 'disabled' })
  await testInfo.attach('Desktop query combined columns', { path: combinedPath, contentType: 'image/png' })

  await openTab(page, 'diagnostics')
  const binding = page.locator('.desktop-usage-binding')
  await binding.locator('summary').click()
  await expect(page.getByLabel('Claude Desktop 额度会话文件', { exact: true }))
    .toHaveValue('D:\\Fixture\\11111111-2222-4333-8444-555555555555.jsonl')
  const instruction = page.getByLabel('Desktop 额度更新指令', { exact: true })
  await expect(instruction).toBeVisible()
  await expect(instruction).toHaveJSProperty('readOnly', true)
  await expect(instruction).toHaveValue(/mcp__ccd_session_mgmt__get_usage/)
  await expect(binding).toContainText('不会自动发送消息')
  await expect(page.getByLabel(/Claude Code 订阅月费/)).toHaveValue('100')
  await expect(page.getByRole('checkbox', { name: '自动推算 Claude 月费', exact: true })).not.toBeChecked()
  const dataSources = page.locator('fieldset').filter({ has: page.locator('legend', { hasText: '数据源' }) })
  const settingsPath = testInfo.outputPath('claude-desktop-query-settings.png')
  await dataSources.screenshot({ path: settingsPath, animations: 'disabled' })
  await testInfo.attach('Desktop query binding settings', { path: settingsPath, contentType: 'image/png' })
})
